-- ---------------------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------------------
CREATE TABLE usuarios (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80)  NOT NULL,
    email  VARCHAR(120) NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE incidencias (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                   VARCHAR(100)  NOT NULL,
    descripcion              VARCHAR(1000),
    prioridad                VARCHAR(10)   NOT NULL,
    estado                   VARCHAR(10)   NOT NULL,
    fecha_creacion           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_id               BIGINT,
    version                  BIGINT        NOT NULL DEFAULT 0,
    categoria                VARCHAR(10)   DEFAULT 'OTROS',
    fecha_limite             DATE,
    auditado_por             VARCHAR(80),
    fecha_ultima_modificacion_estado TIMESTAMP,
    CONSTRAINT fk_incidencias_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_incidencias_prioridad
        CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA')),
    CONSTRAINT ck_incidencias_estado
        CHECK (estado IN ('ABIERTA', 'EN_CURSO', 'CERRADA')),
    CONSTRAINT ck_incidencias_categoria
        CHECK (categoria IN ('HARDWARE', 'SOFTWARE', 'REDES', 'ACCESOS', 'OTROS'))
);

CREATE TABLE comentarios_incidencia (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id BIGINT       NOT NULL,
    autor        VARCHAR(80)  NOT NULL,
    texto        VARCHAR(500) NOT NULL,
    fecha        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comentarios_incidencia
        FOREIGN KEY (incidencia_id) REFERENCES incidencias (id) ON DELETE CASCADE
);

-- El listado y el filtro por estado son las consultas más habituales.
CREATE INDEX idx_incidencias_estado ON incidencias (estado);
CREATE INDEX idx_incidencias_usuario ON incidencias (usuario_id);

