-- ---------------------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------------------
CREATE TABLE usuarios (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80)  NOT NULL,
    email  VARCHAR(120) NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE incidencias (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo         VARCHAR(100)  NOT NULL,
    descripcion    VARCHAR(1000),
    prioridad      VARCHAR(10)   NOT NULL,
    estado         VARCHAR(10)   NOT NULL,
    fecha_creacion TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_id     BIGINT,
    CONSTRAINT fk_incidencias_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_incidencias_prioridad
        CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA')),
    CONSTRAINT ck_incidencias_estado
        CHECK (estado IN ('ABIERTA', 'EN_CURSO', 'CERRADA'))
);

-- El listado y el filtro por estado son las consultas más habituales.
CREATE INDEX idx_incidencias_estado ON incidencias (estado);
CREATE INDEX idx_incidencias_usuario ON incidencias (usuario_id);

